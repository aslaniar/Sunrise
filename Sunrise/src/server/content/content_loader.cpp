/** Emits the S1-3 swap validation line for one domain. */
void report_swap(std::string_view domain,
                 std::size_t jsonCount,
                 std::size_t cacheCount,
                 bool match) noexcept {
    std::array<char, 192> line{};
    const int written = std::snprintf(line.data(),
                                      line.size(),
                                      "ev=s1_loader stage=swap domain=%.*s json=%zu cache=%zu "
                                      "result=%s",
                                      static_cast<int>(domain.size()),
                                      domain.data(),
                                      jsonCount,
                                      cacheCount,
                                      match ? "match" : "mismatch");
    if (written > 0) {
        report({line.data(), static_cast<std::size_t>(written)});
    }
}

/** Reports the exact ability-bucket divergence that stops the boot. */
void report_ability_diff(const AbilityRows& parsed,
                         std::span<const abilities::Definition> cached,
                         std::size_t cachedCount) noexcept {
    const std::size_t common = (std::min)(parsed.count, cachedCount);
    std::size_t first = 0;
    while (first < common && ability_rows_equal(parsed.rows[first], cached[first])) {
        ++first;
    }
    std::array<char, 192> line{};
    const int written =
        std::snprintf(line.data(),
                      line.size(),
                      "ev=s1_loader stage=swap domain=abilityBuckets result=differ "
                      "json_rows=%zu cache_rows=%zu first_diff_row=%zu",
                      parsed.count,
                      cachedCount,
                      first);
    if (written > 0) {
        report({line.data(), static_cast<std::size_t>(written)});
    }
    if (first < common) {
        const abilities::Definition& parsedRow = parsed.rows[first];
        const abilities::Definition& cachedRow = cached[first];
        std::array<char, 192> detail{};
        const int detailWritten = std::snprintf(
            detail.data(),
            detail.size(),
            "ev=s1_loader stage=swap domain=abilityBuckets result=differ row=%zu "
            "json_list=%u cache_list=%u json_sel=%u,%u,%u,%u,%u cache_sel=%u,%u,%u,%u,%u",
            first,
            static_cast<unsigned>(parsedRow.socketEntryListIndex),
            static_cast<unsigned>(cachedRow.socketEntryListIndex),
            static_cast<unsigned>(parsedRow.selection.movementEntry),
            static_cast<unsigned>(parsedRow.selection.grenadeEntry),
            static_cast<unsigned>(parsedRow.selection.superEntry),
            static_cast<unsigned>(parsedRow.selection.meleeEntry),
            static_cast<unsigned>(parsedRow.selection.classEntry),
            static_cast<unsigned>(cachedRow.selection.movementEntry),
            static_cast<unsigned>(cachedRow.selection.grenadeEntry),
            static_cast<unsigned>(cachedRow.selection.superEntry),
            static_cast<unsigned>(cachedRow.selection.meleeEntry),
            static_cast<unsigned>(cachedRow.selection.classEntry));
        if (detailWritten > 0) {
            report({detail.data(), static_cast<std::size_t>(detailWritten)});
        }
    }
}

/** @return True when every parsed row equals the cache-loaded runtime rows. */
template <typename Row, typename Equal>
[[nodiscard]] bool rows_match(const Row* parsed,
                              std::size_t parsedCount,
                              const Row* cached,
                              std::size_t cachedCount,
                              Equal equal) noexcept {
    if (parsedCount != cachedCount) {
        return false;
    }
    for (std::size_t index = 0; index < parsedCount; ++index) {
        if (!equal(parsed[index], cached[index])) {
            return false;
        }
    }
    return true;
}

/** Swaps the inventory-bucket descriptors from the JSON over the cache rows. */
[[nodiscard]] bool swap_buckets(std::span<Node> nodes, std::size_t rowsNode) noexcept {
    static BucketRows parsed{};
    static std::array<buckets::Descriptor, buckets::kDescriptorCapacity> cached{};
    if (!parse_buckets(nodes, rowsNode, parsed)) {
        report_fail("inventoryBuckets", "parse");
        return false;
    }
    std::size_t cachedCount = 0;
    const bool match =
        buckets::snapshot(cached, cachedCount)
        && rows_match(parsed.rows.data(),
                      parsed.count,
                      cached.data(),
                      cachedCount,
                      bucket_rows_equal);
    report_swap("inventoryBuckets", parsed.count, cachedCount, match);
    if (!buckets::replace(std::span(parsed.rows).first(parsed.count))) {
        report_fail("inventoryBuckets", "reject");
        return false;
    }
    return true;
}

