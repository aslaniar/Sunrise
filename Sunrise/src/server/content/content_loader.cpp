/** Parses the bucket descriptors and sorts them by bucketId (S1RD-08). */
[[nodiscard]] bool parse_buckets(std::span<Node> nodes,
                                 std::size_t rowsNode,
                                 BucketRows& output) noexcept {
    const Node& rows = nodes[rowsNode];
    if (rows.kind != Node::Kind::array || rows.childCount == 0) {
        return false;
    }
    output.count = 0;
    for (std::size_t index = 0; index < rows.childCount; ++index) {
        if (output.count >= output.rows.size()) {
            return false;
        }
        const std::size_t rowNode = element(nodes, rowsNode, index);
        if (rowNode == kNpos || nodes[rowNode].kind != Node::Kind::object) {
            return false;
        }
        std::uint64_t bucketId = 0;
        std::uint64_t selector = 0;
        std::uint64_t firstSlot = 0;
        std::uint64_t slotCount = 0;
        if (!member_number(nodes, rowNode, "bucketId", bucketId, 0xFF)
            || !member_number(nodes, rowNode, "arraySelector", selector, 0xFF)
            || !member_number(nodes, rowNode, "firstSlot", firstSlot, 0xFFFF)
            || !member_number(nodes, rowNode, "slotCount", slotCount, 0xFFFF)) {
            return false;
        }
        output.rows[output.count] = {
            static_cast<std::uint8_t>(bucketId),
            static_cast<buckets::ArraySelector>(selector),
            static_cast<std::uint16_t>(firstSlot),
            static_cast<std::uint16_t>(slotCount),
        };
        ++output.count;
    }
    std::sort(output.rows.begin(),
              output.rows.begin() + static_cast<std::ptrdiff_t>(output.count),
              [](const buckets::Descriptor& left, const buckets::Descriptor& right) {
                  return left.bucketId < right.bucketId;
              });
    return true;
}

/** Parses the dense socket-entry-list rows and sorts them by definitionIndex. */
[[nodiscard]] bool parse_socket_lists(std::span<Node> nodes,
                                      std::size_t rowsNode,
                                      SocketListRows& output) noexcept {
    const Node& rows = nodes[rowsNode];
    if (rows.kind != Node::Kind::array || rows.childCount == 0) {
        return false;
    }
    output.count = 0;
    for (std::size_t index = 0; index < rows.childCount; ++index) {
        if (output.count >= output.rows.size()) {
            return false;
        }
        const std::size_t rowNode = element(nodes, rowsNode, index);
        if (rowNode == kNpos || nodes[rowNode].kind != Node::Kind::object) {
            return false;
        }
        std::uint64_t definitionHash = 0;
        std::uint64_t definitionIndex = 0;
        std::uint64_t entryCount = 0;
        std::uint64_t readyMask = 0;
        if (!member_number(nodes, rowNode, "definitionHash", definitionHash, 0xFFFFFFFFULL)
            || !member_number(nodes, rowNode, "definitionIndex", definitionIndex, 0xFFFF)
            || !member_number(nodes, rowNode, "entryCount", entryCount, 0xFF)
            || !member_number(nodes, rowNode, "readyMask", readyMask,
                              (std::numeric_limits<std::uint64_t>::max)())) {
            return false;
        }
        output.rows[output.count] = {
            static_cast<std::uint32_t>(definitionHash),
            static_cast<std::uint16_t>(definitionIndex),
            static_cast<std::uint8_t>(entryCount),
            readyMask,
        };
        ++output.count;
    }
    std::sort(output.rows.begin(),
              output.rows.begin() + static_cast<std::ptrdiff_t>(output.count),
              [](const socket_lists::Definition& left, const socket_lists::Definition& right) {
                  return left.definitionIndex < right.definitionIndex;
              });
    return true;
}

/** Parses the per-list entry tables, padding every tail with the default Entry (S1RD-08). */
[[nodiscard]] bool parse_entry_tables(std::span<Node> nodes,
                                      std::size_t rowsNode,
                                      EntryTableRows& output) noexcept {
    const Node& rows = nodes[rowsNode];
    if (rows.kind != Node::Kind::array || rows.childCount == 0) {
        return false;
    }
    output.count = 0;
    for (std::size_t index = 0; index < rows.childCount; ++index) {
        if (output.count >= output.rows.size()) {
            return false;
        }
        const std::size_t rowNode = element(nodes, rowsNode, index);
        if (rowNode == kNpos || nodes[rowNode].kind != Node::Kind::object) {
            return false;
        }
        std::uint64_t definitionIndex = 0;
        std::uint64_t entryCount = 0;
        if (!member_number(nodes, rowNode, "definitionIndex", definitionIndex, 0xFFFF)
            || !member_number(nodes, rowNode, "entryCount", entryCount,
                              socket_lists::kEntryCapacity)) {
            return false;
        }
        const std::size_t entriesNode = member_array(nodes, rowNode, "entries");
        if (entriesNode == kNpos || nodes[entriesNode].childCount != entryCount) {
            return false;
        }
        socket_lists::EntryTable table{};
        table.definitionIndex = static_cast<std::uint16_t>(definitionIndex);
        for (std::size_t entry = 0; entry < entryCount; ++entry) {
            const std::size_t entryNode = element(nodes, entriesNode, entry);
            if (entryNode == kNpos || nodes[entryNode].kind != Node::Kind::object) {
                return false;
            }
            std::string_view plugSourceText;
            std::uint64_t group = 0;
            std::uint64_t kind = 0;
            std::uint32_t plugSource = 0;
            if (!member_string(nodes, entryNode, "plugSource", plugSourceText)
                || !parse_hex_u32(plugSourceText, plugSource)
                || !member_number(nodes, entryNode, "group", group, 0xFF)
                || !member_number(nodes, entryNode, "kind", kind, 0xFF)) {
                return false;
            }
            table.entries[entry] = {
                plugSource,
                static_cast<std::uint8_t>(group),
                static_cast<std::uint8_t>(kind),
            };
        }
        // The EntryTable aggregate default is exactly the cache's padded tail row
        // {plugSource 0, group 0xFF, kind 0}, so lanes entryCount..35 stay defaulted.
        output.rows[output.count] = table;
        ++output.count;
    }
    std::sort(output.rows.begin(),
              output.rows.begin() + static_cast<std::ptrdiff_t>(output.count),
              [](const socket_lists::EntryTable& left, const socket_lists::EntryTable& right) {
                  return left.definitionIndex < right.definitionIndex;
              });
    return true;
}

/** Parses the ability-bucket rows and sorts them into the cache's ability_less order. */
[[nodiscard]] bool parse_ability_rows(std::span<Node> nodes,
                                      std::size_t rowsNode,
                                      AbilityRows& output) noexcept {
    const Node& rows = nodes[rowsNode];
    if (rows.kind != Node::Kind::array || rows.childCount == 0) {
        return false;
    }
    output.count = 0;
    for (std::size_t index = 0; index < rows.childCount; ++index) {
        if (output.count >= output.rows.size()) {
            return false;
        }
        const std::size_t rowNode = element(nodes, rowsNode, index);
        if (rowNode == kNpos || nodes[rowNode].kind != Node::Kind::object) {
            return false;
        }
        std::uint64_t socketEntryListIndex = 0;
        if (!member_number(nodes, rowNode, "socketEntryListIndex", socketEntryListIndex, 0xFFFF)) {
            return false;
        }
        const std::size_t selectionNode = member_array(nodes, rowNode, "selection");
        if (selectionNode == kNpos || nodes[selectionNode].childCount != 5) {
            return false;
        }
        std::uint64_t selection[5] = {};
        for (std::size_t lane = 0; lane < 5; ++lane) {
            if (!element_number(nodes, selectionNode, lane, selection[lane], 0xFF)) {
                return false;
            }
        }
        const std::size_t overflowNode = member_array(nodes, rowNode, "overflow");
        if (overflowNode == kNpos
            || nodes[overflowNode].childCount > abilities::kOverflowCapacity) {
            return false;
        }
        const std::size_t bucketsNode = member_array(nodes, rowNode, "buckets");
        if (bucketsNode == kNpos
            || nodes[bucketsNode].childCount != abilities::kBucketCapacity) {
            return false;
        }

        abilities::Definition definition{};
        definition.socketEntryListIndex = static_cast<std::uint16_t>(socketEntryListIndex);
        definition.selection = {
            static_cast<std::uint8_t>(selection[0]),
            static_cast<std::uint8_t>(selection[1]),
            static_cast<std::uint8_t>(selection[2]),
            static_cast<std::uint8_t>(selection[3]),
            static_cast<std::uint8_t>(selection[4]),
        };
        definition.overflowCount = static_cast<std::uint8_t>(nodes[overflowNode].childCount);
        for (std::size_t lane = 0; lane < nodes[overflowNode].childCount; ++lane) {
            std::uint64_t hash = 0;
            if (!element_number(nodes, overflowNode, lane, hash, 0xFFFFFFFFULL)) {
                return false;
            }
            definition.overflow[lane] = static_cast<std::uint32_t>(hash);
        }
        for (std::size_t bucket = 0; bucket < abilities::kBucketCapacity; ++bucket) {
            const std::size_t bucketNode = element(nodes, bucketsNode, bucket);
            if (bucketNode == kNpos || nodes[bucketNode].kind != Node::Kind::object) {
                return false;
            }
            std::uint64_t kind = 0;
            if (!member_number(nodes, bucketNode, "kind", kind, 0xFF)) {
                return false;
            }
            const std::size_t hashesNode = member_array(nodes, bucketNode, "hashes");
            if (hashesNode == kNpos
                || nodes[hashesNode].childCount > abilities::kBucketHashCapacity) {
                return false;
            }
            abilities::Bucket& target = definition.buckets[bucket];
            target.kind = static_cast<std::uint8_t>(kind);
            target.hashCount = static_cast<std::uint8_t>(nodes[hashesNode].childCount);
            for (std::size_t hash = 0; hash < nodes[hashesNode].childCount; ++hash) {
                std::uint64_t value = 0;
                if (!element_number(nodes, hashesNode, hash, value, 0xFFFFFFFFULL)) {
                    return false;
                }
                target.hashes[hash] = static_cast<std::uint32_t>(value);
            }
        }
        output.rows[output.count] = definition;
        ++output.count;
    }
    const auto selectionKey = [](const abilities::Selection& selection) noexcept {
        return std::array<std::uint8_t, 5>{selection.movementEntry,
                                           selection.grenadeEntry,
                                           selection.superEntry,
                                           selection.meleeEntry,
                                           selection.classEntry};
    };
    std::sort(output.rows.begin(),
              output.rows.begin() + static_cast<std::ptrdiff_t>(output.count),
              [&selectionKey](const abilities::Definition& left,
                              const abilities::Definition& right) {
                  if (left.socketEntryListIndex != right.socketEntryListIndex) {
                      return left.socketEntryListIndex < right.socketEntryListIndex;
                  }
                  return selectionKey(left.selection) < selectionKey(right.selection);
              });
    return true;
}

/** Parses the progression rows, reducing the native scope (S1RD-08). */
[[nodiscard]] bool parse_progressions(std::span<Node> nodes,
                                      std::size_t rowsNode,
                                      ProgressionRows& output) noexcept {
    const Node& rows = nodes[rowsNode];
    if (rows.kind != Node::Kind::array || rows.childCount == 0) {
        return false;
    }
    output.count = 0;
    for (std::size_t index = 0; index < rows.childCount; ++index) {
        if (output.count >= output.rows.size()) {
            return false;
        }
        const std::size_t rowNode = element(nodes, rowsNode, index);
        if (rowNode == kNpos || nodes[rowNode].kind != Node::Kind::object) {
            return false;
        }
        std::uint64_t definitionIndex = 0;
        std::uint64_t scopeRaw = 0;
        if (!member_number(nodes, rowNode, "definitionIndex", definitionIndex, 0xFFFF)
            || !member_number(nodes, rowNode, "scopeRaw", scopeRaw, 0xFF)) {
            return false;
        }
        const std::uint8_t reduced =
            scopeRaw <= static_cast<std::uint64_t>(progressions::Scope::character)
                ? static_cast<std::uint8_t>(scopeRaw)
                : static_cast<std::uint8_t>(progressions::Scope::unreplicated);
        // Cross-check the emitter's own reduction so both producers cannot drift silently.
        std::uint64_t emittedScope = 0;
        if (member_number(nodes, rowNode, "scope", emittedScope, 0xFF)
            && emittedScope != reduced) {
            return false;
        }
        output.rows[output.count] = {
            static_cast<std::uint16_t>(definitionIndex),
            static_cast<progressions::Scope>(reduced),
        };
        ++output.count;
    }
    std::sort(output.rows.begin(),
              output.rows.begin() + static_cast<std::ptrdiff_t>(output.count),
              [](const progressions::Definition& left, const progressions::Definition& right) {
                  return left.definitionIndex < right.definitionIndex;
              });
    return true;
}

// ---------------------------------------------------------------------------
// Row equality (JSON side vs cache-loaded runtime side, both canonicalized).
// ---------------------------------------------------------------------------

[[nodiscard]] bool bucket_rows_equal(const buckets::Descriptor& left,
                                     const buckets::Descriptor& right) noexcept {
    return left.bucketId == right.bucketId && left.arraySelector == right.arraySelector
           && left.firstSlot == right.firstSlot && left.slotCount == right.slotCount;
}

[[nodiscard]] bool socket_list_rows_equal(const socket_lists::Definition& left,
                                          const socket_lists::Definition& right) noexcept {
    return left.definitionHash == right.definitionHash
           && left.definitionIndex == right.definitionIndex
           && left.entryCount == right.entryCount && left.readyMask == right.readyMask;
}

[[nodiscard]] bool entry_table_rows_equal(const socket_lists::EntryTable& left,
                                          const socket_lists::EntryTable& right) noexcept {
    if (left.definitionIndex != right.definitionIndex) {
        return false;
    }
    for (std::size_t index = 0; index < socket_lists::kEntryCapacity; ++index) {
        if (left.entries[index].plugSource != right.entries[index].plugSource
            || left.entries[index].group != right.entries[index].group
            || left.entries[index].kind != right.entries[index].kind) {
            return false;
        }
    }
    return true;
}

[[nodiscard]] bool ability_rows_equal(const abilities::Definition& left,
                                      const abilities::Definition& right) noexcept {
    if (left.socketEntryListIndex != right.socketEntryListIndex
        || left.selection != right.selection || left.overflowCount != right.overflowCount) {
        return false;
    }
    for (std::size_t bucket = 0; bucket < abilities::kBucketCapacity; ++bucket) {
        const abilities::Bucket& leftBucket = left.buckets[bucket];
        const abilities::Bucket& rightBucket = right.buckets[bucket];
        if (leftBucket.kind != rightBucket.kind
            || leftBucket.hashCount != rightBucket.hashCount) {
            return false;
        }
        for (std::size_t hash = 0; hash < abilities::kBucketHashCapacity; ++hash) {
            if (leftBucket.hashes[hash] != rightBucket.hashes[hash]) {
                return false;
            }
        }
    }
    for (std::size_t overflow = 0; overflow < abilities::kOverflowCapacity; ++overflow) {
        if (left.overflow[overflow] != right.overflow[overflow]) {
            return false;
        }
    }
    return true;
}

[[nodiscard]] bool progression_rows_equal(const progressions::Definition& left,
                                          const progressions::Definition& right) noexcept {
    return left.definitionIndex == right.definitionIndex && left.scope == right.scope;
}

