// ---------------------------------------------------------------------------
// Reporting (defined before the row extractors, which use it for diagnostics).
// ---------------------------------------------------------------------------

/** Emits one validation line on the console and through the log. */
void report(std::string_view line) noexcept {
    std::fwrite(line.data(), 1, line.size(), stdout);
    std::fputc('\n', stdout);
    std::fflush(stdout);
    core::log::write(core::log::Channel::state, core::log::Level::info, line);
}

/** Emits one loader failure line naming the domain and the failing step. */
void report_fail(std::string_view domain, std::string_view reason) noexcept {
    std::array<char, 192> line{};
    const int written = std::snprintf(line.data(),
                                      line.size(),
                                      "ev=s1_loader stage=swap domain=%.*s result=fail "
                                      "reason=%.*s",
                                      static_cast<int>(domain.size()),
                                      domain.data(),
                                      static_cast<int>(reason.size()),
                                      reason.data());
    if (written > 0) {
        report({line.data(), static_cast<std::size_t>(written)});
    }
}

