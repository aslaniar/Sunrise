/** The generated domain files stay far under this fixed read buffer. */
constexpr std::size_t kJsonCapacity = 2 * 1024 * 1024;
/** Largest JSON value count the fixed parser arena accepts. */
constexpr std::size_t kNodeCapacity = 262144;
/** Sentinel arena index meaning "not present". */
constexpr std::size_t kNpos = (std::numeric_limits<std::size_t>::max)();

// ---------------------------------------------------------------------------
// Minimal JSON parser over the deterministic domain-file shape (generated by the S1-3
// decode lane's Python emitter): objects, arrays, integers, and plain ASCII strings.
// Anything else (escapes, floats, deep nesting) is refused.
//
// Arena model: one fixed node arena. A container's children are LINKED through each
// child's nextChild field (objects link their keys; arrays link their elements), because
// a child value that is itself a container appends its own descendants into the arena
// between the parent's children. An object member's value node always sits exactly one
// arena slot after its key node (value() appends the value node before any descendants).
// ---------------------------------------------------------------------------

/** One parsed JSON value. Objects link keys via nextChild; arrays link elements. */
struct Node {
    enum class Kind : std::uint8_t { invalid, null, boolean, number, string, array, object };

    Kind kind{Kind::invalid};
    bool booleanValue{};
    std::int64_t numberValue{};
    std::string_view text{};
    std::size_t firstChild{kNpos};
    std::size_t childCount{};
    std::size_t nextChild{kNpos};
};

/** @return One array element by position, or npos. */
[[nodiscard]] std::size_t element(std::span<Node> nodes,
                                  std::size_t arrayNode,
                                  std::size_t index) noexcept {
    const Node& array = nodes[arrayNode];
    if (array.kind != Node::Kind::array || index >= array.childCount) {
        return kNpos;
    }
    std::size_t node = array.firstChild;
    for (std::size_t step = 0; step < index; ++step) {
        if (node == kNpos || node >= nodes.size()) {
            return kNpos;
        }
        node = nodes[node].nextChild;
    }
    return node < nodes.size() ? node : kNpos;
}

/** @return Index of one object member's value node, or npos. */
[[nodiscard]] std::size_t find_member(std::span<Node> nodes,
                                      std::size_t objectNode,
                                      std::string_view name) noexcept {
    const Node& object = nodes[objectNode];
    if (object.kind != Node::Kind::object) {
        return kNpos;
    }
    std::size_t key = object.firstChild;
    while (key != kNpos && key < nodes.size()) {
        const Node& keyNode = nodes[key];
        const std::size_t value = key + 1;
        if (keyNode.kind == Node::Kind::string && keyNode.text == name
            && value < nodes.size()) {
            return value;
        }
        key = keyNode.nextChild;
    }
    return kNpos;
}

/** Reads one required nonnegative integer member inside its maximum. */
[[nodiscard]] bool member_number(std::span<Node> nodes,
                                 std::size_t objectNode,
                                 std::string_view name,
                                 std::uint64_t& output,
                                 std::uint64_t maximum) noexcept {
    const std::size_t member = find_member(nodes, objectNode, name);
    if (member == kNpos) {
        return false;
    }
    const Node& value = nodes[member];
    if (value.kind != Node::Kind::number || value.numberValue < 0) {
        return false;
    }
    const auto number = static_cast<std::uint64_t>(value.numberValue);
    if (number > maximum) {
        return false;
    }
    output = number;
    return true;
}

/** Reads one required string member. */
[[nodiscard]] bool member_string(std::span<Node> nodes,
                                 std::size_t objectNode,
                                 std::string_view name,
                                 std::string_view& output) noexcept {
    const std::size_t member = find_member(nodes, objectNode, name);
    if (member == kNpos) {
        return false;
    }
    const Node& value = nodes[member];
    if (value.kind != Node::Kind::string) {
        return false;
    }
    output = value.text;
    return true;
}

/** @return Index of one required array member, or npos. */
[[nodiscard]] std::size_t member_array(std::span<Node> nodes,
                                       std::size_t objectNode,
                                       std::string_view name) noexcept {
    const std::size_t member = find_member(nodes, objectNode, name);
    if (member == kNpos || nodes[member].kind != Node::Kind::array) {
        return kNpos;
    }
    return member;
}

/** Reads one array element as a nonnegative integer inside its maximum. */
[[nodiscard]] bool element_number(std::span<Node> nodes,
                                  std::size_t arrayNode,
                                  std::size_t index,
                                  std::uint64_t& output,
                                  std::uint64_t maximum) noexcept {
    const std::size_t elementNode = element(nodes, arrayNode, index);
    if (elementNode == kNpos) {
        return false;
    }
    const Node& value = nodes[elementNode];
    if (value.kind != Node::Kind::number || value.numberValue < 0) {
        return false;
    }
    const auto number = static_cast<std::uint64_t>(value.numberValue);
    if (number > maximum) {
        return false;
    }
    output = number;
    return true;
}

/** Parses "0x" + up to 8 hex digits into a 32-bit plug-source hash. */
[[nodiscard]] bool parse_hex_u32(std::string_view text, std::uint32_t& output) noexcept {
    if (text.size() < 3 || text[0] != '0' || (text[1] != 'x' && text[1] != 'X')) {
        return false;
    }
    std::uint32_t value = 0;
    for (std::size_t index = 2; index < text.size(); ++index) {
        const char digit = text[index];
        unsigned nibble = 0;
        if (digit >= '0' && digit <= '9') {
            nibble = static_cast<unsigned>(digit - '0');
        } else if (digit >= 'a' && digit <= 'f') {
            nibble = static_cast<unsigned>(digit - 'a') + 10;
        } else if (digit >= 'A' && digit <= 'F') {
            nibble = static_cast<unsigned>(digit - 'A') + 10;
        } else {
            return false;
        }
        value = value * 16 + nibble;
    }
    output = value;
    return true;
}

/** Bounded recursive-descent parser over one domain file's JSON text. */
class Parser final {
public:
    Parser(std::string_view input, std::span<Node> nodes) noexcept : input_(input), nodes_(nodes) {}

    /** Parses one complete document into the arena root. */
    [[nodiscard]] bool parse(std::size_t& root) noexcept {
        if (nodes_.empty()) {
            return false;
        }
        skip_whitespace();
        root = 0;
        if (!value(root)) {
            return false;
        }
        skip_whitespace();
        return position_ == input_.size();
    }

    /** @return Current parse position, for failure diagnostics. */
    [[nodiscard]] std::size_t position() const noexcept {
        return position_;
    }

    /** @return One input byte at an index, or 0 past the end. */
    [[nodiscard]] std::uint8_t byte_at(std::size_t index) const noexcept {
        return index < input_.size() ? static_cast<std::uint8_t>(input_[index]) : 0;
    }

private:
    [[nodiscard]] bool value(std::size_t& node) noexcept {
        skip_whitespace();
        if (position_ >= input_.size()) {
            return false;
        }
        const char next = input_[position_];
        if (next == '{') {
            return object(node);
        }
        if (next == '[') {
            return array(node);
        }
        if (next == '"') {
            return string(node);
        }
        if (next == 't' || next == 'f') {
            return literal(node, "true", true) || literal(node, "false", false);
        }
        if (next == 'n') {
            return literal(node, "null", false);
        }
        return number(node);
    }

    [[nodiscard]] bool object(std::size_t& node) noexcept {
        if (!consume('{')) {
            return false;
        }
        const std::size_t container = append(Node::Kind::object);
        if (container == kNpos) {
            return false;
        }
        if (consume('}')) {
            node = container;
            return true;
        }
        std::size_t previousKey = kNpos;
        for (;;) {
            std::size_t key = 0;
            std::size_t member = 0;
            if (!string(key) || !consume(':') || !value(member)) {
                return false;
            }
            // The member value node is the first node value() appends, so it always sits right
            // after its key node; keys form the member chain.
            Node& containerNode = nodes_[container];
            if (previousKey == kNpos) {
                containerNode.firstChild = key;
            } else {
                nodes_[previousKey].nextChild = key;
            }
            previousKey = key;
            ++containerNode.childCount;
            if (consume('}')) {
                break;
            }
            if (!consume(',')) {
                return false;
            }
        }
        node = container;
        return true;
    }

    [[nodiscard]] bool array(std::size_t& node) noexcept {
        if (!consume('[')) {
            return false;
        }
        const std::size_t container = append(Node::Kind::array);
        if (container == kNpos) {
            return false;
        }
        if (consume(']')) {
            node = container;
            return true;
        }
        std::size_t previousElement = kNpos;
        for (;;) {
            std::size_t elementNode = 0;
            if (!value(elementNode)) {
                return false;
            }
            Node& containerNode = nodes_[container];
            if (previousElement == kNpos) {
                containerNode.firstChild = elementNode;
            } else {
                nodes_[previousElement].nextChild = elementNode;
            }
            previousElement = elementNode;
            ++containerNode.childCount;
            if (consume(']')) {
                break;
            }
            if (!consume(',')) {
                return false;
            }
        }
        node = container;
        return true;
    }

    [[nodiscard]] bool string(std::size_t& node) noexcept {
        skip_whitespace();
        if (position_ >= input_.size() || input_[position_] != '"') {
            return false;
        }
        const std::size_t start = ++position_;
        while (position_ < input_.size() && input_[position_] != '"') {
            // The generated domain files carry plain ASCII; an escape would mean an unexpected
            // producer and is refused.
            if (input_[position_] == '\\') {
                return false;
            }
            ++position_;
        }
        if (position_ >= input_.size()) {
            return false;
        }
        const std::string_view text = input_.substr(start, position_ - start);
        ++position_;
        const std::size_t index = append(Node::Kind::string);
        if (index == kNpos) {
            return false;
        }
        nodes_[index].text = text;
        node = index;
        return true;
    }

    [[nodiscard]] bool number(std::size_t& node) noexcept {
        const std::size_t start = position_;
        if (position_ < input_.size() && input_[position_] == '-') {
            ++position_;
        }
        if (position_ >= input_.size() || !is_digit(input_[position_])) {
            position_ = start;
            return false;
        }
        std::uint64_t magnitude = 0;
        while (position_ < input_.size() && is_digit(input_[position_])) {
            magnitude = magnitude * 10 + static_cast<std::uint64_t>(input_[position_] - '0');
            if (magnitude > static_cast<std::uint64_t>((std::numeric_limits<std::int64_t>::max)())) {
                position_ = start;
                return false;
            }
            ++position_;
        }
        // The generated domain files carry integers only.
        if (position_ < input_.size()
            && (input_[position_] == '.' || input_[position_] == 'e' || input_[position_] == 'E')) {
            position_ = start;
            return false;
        }
        const std::size_t index = append(Node::Kind::number);
        if (index == kNpos) {
            return false;
        }
        const bool negative = start < position_ && input_[start] == '-';
        nodes_[index].numberValue =
            negative ? -static_cast<std::int64_t>(magnitude) : static_cast<std::int64_t>(magnitude);
        node = index;
        return true;
    }

    [[nodiscard]] bool literal(std::size_t& node,
                               std::string_view text,
                               bool booleanValue) noexcept {
        if (input_.substr(position_, text.size()) != text) {
            return false;
        }
        position_ += text.size();
        const std::size_t index = append(Node::Kind::boolean);
        if (index == kNpos) {
            return false;
        }
        nodes_[index].booleanValue = booleanValue;
        node = index;
        return true;
    }

    [[nodiscard]] std::size_t append(Node::Kind kind) noexcept {
        if (nodeCount_ >= nodes_.size()) {
            return kNpos;
        }
        nodes_[nodeCount_] = Node{kind};
        return nodeCount_++;
    }

    [[nodiscard]] bool consume(char expected) noexcept {
        skip_whitespace();
        if (position_ >= input_.size() || input_[position_] != expected) {
            return false;
        }
        ++position_;
        return true;
    }

    void skip_whitespace() noexcept {
        while (position_ < input_.size()) {
            const char value = input_[position_];
            if (value != ' ' && value != '\t' && value != '\r' && value != '\n') {
                return;
            }
            ++position_;
        }
    }

    [[nodiscard]] static bool is_digit(char value) noexcept {
        return value >= '0' && value <= '9';
    }

    std::string_view input_;
    std::span<Node> nodes_;
    std::size_t position_{};
    std::size_t nodeCount_{};
};

